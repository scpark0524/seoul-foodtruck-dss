def build():
    ss = standardize_sales(load_one("sales_dong"))
    n2c = build_dong_name_to_cd(ss)             # 행정동명 → 8자리 코드
    rows, unresolved = [], []
    for spot, (dong, conf) in SPOT_TO_DONG_NM.items():
        code = n2c.get(dong)
        if code is None:
            unresolved.append((spot, dong))
        rows.append({"AREA_NM": spot, "dong_nm": dong,
                     "adstr_cd": code, "conf": conf})
    df = pd.DataFrame(rows)
    out = ROOT / "scripts" / "spot_to_dong.csv"
    df.to_csv(out, index=False, encoding="utf-8-sig")
    print(f"[SAVED] {out}  ({len(df)}개 spot, 코드해결 {df['adstr_cd'].notna().sum()}개)")
    if unresolved:
        print(f"[확인필요] 행정동명 불일치 {len(unresolved)}개:")
        for s, d in unresolved: print(f"   - {s} → '{d}' (행정동 목록에 없음)")
    return df


if __name__ == "__main__":
    build()
